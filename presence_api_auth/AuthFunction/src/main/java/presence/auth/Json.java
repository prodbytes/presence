package presence.auth;

/** Just enough JSON: a quoted, escaped string. */
final class Json {

    private Json() {
    }

    static String string(String value) {
        var out = new StringBuilder(value.length() + 2).append('"');
        for (var c : value.toCharArray()) {
            switch (c) {
                case '"' -> out.append("\\\"");
                case '\\' -> out.append("\\\\");
                case '\n' -> out.append("\\n");
                case '\r' -> out.append("\\r");
                case '\t' -> out.append("\\t");
                default -> {
                    if (c < 0x20) {
                        out.append(String.format("\\u%04x", (int) c));
                    } else {
                        out.append(c);
                    }
                }
            }
        }
        return out.append('"').toString();
    }
}
